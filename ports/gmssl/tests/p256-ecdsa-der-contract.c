#include <gmssl/ecdsa.h>

#include <stdint.h>
#include <stdio.h>
#include <string.h>

enum {
    P256_SCALAR_BYTES = 32,
    DER_SENTINEL_BYTES = 1,
};

static int check_signature(
    const char *case_name,
    const uint8_t *der_storage,
    size_t der_storage_length,
    const uint8_t expected_r[P256_SCALAR_BYTES],
    const uint8_t expected_s[P256_SCALAR_BYTES])
{
    uint8_t actual_r[P256_SCALAR_BYTES];
    uint8_t actual_s[P256_SCALAR_BYTES];
    ECDSA_SIGNATURE signature;
    const uint8_t *input = der_storage;
    size_t input_length;

    if (!case_name || !der_storage || der_storage_length <= DER_SENTINEL_BYTES
        || !expected_r || !expected_s) {
        fprintf(stderr, "invalid contract input\n");
        return 4;
    }

    input_length = der_storage_length - DER_SENTINEL_BYTES;
    memset(&signature, 0, sizeof(signature));
    if (ecdsa_signature_from_der(&signature, &input, &input_length) != 1) {
        fprintf(stderr, "%s: DER parse failed\n", case_name);
        return 2;
    }
    if (input_length != 0
        || input != der_storage + der_storage_length - DER_SENTINEL_BYTES) {
        fprintf(stderr, "%s: DER parser did not consume the signature\n", case_name);
        return 3;
    }

    secp256r1_to_32bytes(signature.r, actual_r);
    secp256r1_to_32bytes(signature.s, actual_s);
    if (memcmp(actual_r, expected_r, sizeof(actual_r)) != 0
        || memcmp(actual_s, expected_s, sizeof(actual_s)) != 0) {
        fprintf(stderr, "%s: short scalar was not left padded\n", case_name);
        return 1;
    }
    return 0;
}

